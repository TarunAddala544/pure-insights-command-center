// Generates docs/DATA_PROFILE.md and docs/DATA_QUALITY_REPORT.md from the CSV and the SQL suite (no hand-typed numbers).
import fs from 'node:fs';
import path from 'node:path';
import { loadConfig } from '../backend/src/config/index.js';
import { ingest, median, round } from '../backend/src/domain/clean.js';
import { Database } from '../backend/src/repositories/db.js';
import { buildWarehouse } from '../backend/src/repositories/warehouseRepository.js';

const cfg = loadConfig();
const data = ingest(cfg.csvPath);
const { rows, summary: s } = data;
const db = await Database.open();
await buildWarehouse(db, rows, cfg.sqlDir, cfg.creditPriceUsd);
const golden = JSON.parse(fs.readFileSync(path.join(cfg.root, 'validation/golden.json'), 'utf8'));

const pct = (arr, p) => [...arr].sort((a, b) => a - b)[Math.min(arr.length - 1, Math.floor((p / 100) * arr.length))];
const col = (f) => rows.map(f);
const stat = (name, v) =>
  `| ${name} | ${Math.min(...v)} | ${round(median(v), 2)} | ${round(pct(v, 90), 2)} | ${Math.max(...v)} | ${round(v.reduce((a, b) => a + b, 0) / v.length, 2)} |`;
const statuses = Object.entries(Object.groupBy(rows, (r) => r.refreshStatus))
  .map(([k, v]) => `${k}: ${v.length}`)
  .join(', ');
const sev = { warn: golden.sev_warn, high: golden.sev_high, crit: golden.sev_crit };
const stamp = `_Generated by \`scripts/gen-docs.js\` from \`data/Case_Study_3_Pure_Insights_Monitoring.csv\` (sha256 \`${golden.csv_sha256}\`). Do not edit by hand._`;

fs.writeFileSync(
  path.join(cfg.root, 'docs/DATA_PROFILE.md'),
  `# Data profile (Phase 0)

${stamp}

* **Rows:** ${s.rows}; **columns (10):** report_id, report_name, owner_email, last_refresh_status, monthly_active_views, snowflake_credits_consumed, avg_load_time_sec, aws_hosting_cost_usd, query_count_last_30d, concurrent_user_peak.
* **Structure:** report_id cycles RPT_200..RPT_299 exactly 20 times in file order. Each block of 100 consecutive rows is one **sweep** (a roll call of all 100 reports). There is **no timestamp column**; timestamps in this project are synthetic (sweep = one day from 2026-09-01).
* **Nulls:** none in the CSV sense. Missing owners are the **literal text \`nan\`** (${s.orphanMissingRows} rows) plus the sentinel \`ORPHANED_REPORT\` (${s.orphanSentinelRows} rows). A naive \`pd.read_csv\` turns \`nan\` into NaN; the loader here reads everything as text first.
* **Types:** all numeric columns parse cleanly (the loader rejects any unparsable value loudly).
* **Duplicates:** no duplicate (report, sweep) pairs.
* **The data is synthetic.** Every numeric column is statistically independent of the others (Pearson views vs AWS cost = ${s.viewsAwsPearson}). Findings describe this file, not a real platform.

| Column | min | median | p90 | max | mean |
|---|---|---|---|---|---|
${stat(
  'monthly_active_views',
  col((r) => r.monthly_active_views),
)}
${stat(
  'snowflake_credits_consumed',
  col((r) => r.snowflake_credits_consumed),
)}
${stat(
  'avg_load_time_sec',
  col((r) => r.avg_load_time_sec),
)}
${stat(
  'aws_hosting_cost_usd',
  col((r) => r.aws_hosting_cost_usd),
)}
${stat(
  'query_count_last_30d',
  col((r) => r.query_count_last_30d),
)}
${stat(
  'concurrent_user_peak',
  col((r) => r.concurrent_user_peak),
)}

* **Refresh status:** ${statuses}.
* **Latency distribution:** ${s.latencyGt15} of ${s.rows} rows (${round((s.latencyGt15 / s.rows) * 100, 1)}%) exceed 15 s; ${s.latencyExactly15} are exactly 15.0 (not breaches: the rule is strict). Tiers: WARN ${sev.warn}, HIGH ${sev.high}, CRIT ${sev.crit}. Median ${round(median(col((r) => r.avg_load_time_sec)), 1)} s is above the threshold, so the 15 s rule is **saturated**.
* **Zero-view rows:** ${s.zeroViewRows}. **Rows where concurrent peak > monthly views (impossible):** ${s.peakGtViewsRows}.
`,
);

const q = (await db.all('SELECT snapshot_id, report_id, sweep, raw_value FROM DQ_QUARANTINE ORDER BY snapshot_id LIMIT 5'))
  .map((r) => `| ${r.snapshot_id} | ${r.report_id} | ${r.sweep} | ${r.raw_value} |`)
  .join('\n');
const outl = data.outliers
  .slice(0, 5)
  .map((o) => `| ${o.snapshotId} | ${o.reportId} | ${o.z} |`)
  .join('\n');
fs.writeFileSync(
  path.join(cfg.root, 'docs/DATA_QUALITY_REPORT.md'),
  `# Data quality report

${stamp}

All counts are produced three independent ways and asserted equal in tests: Node ingestion (\`backend/src/domain/clean.js\`), the SQL suite (\`sql/02_load_clean.sql\`, \`03_anomaly_filtering.sql\`), and the pandas verifier (\`validation/verify.py\`).

## Defect 1: Orphaned reports (missing owner)

* **Detection rule:** \`owner_email\`, trimmed and case-insensitive, is NULL, empty, \`nan\`, \`none\`, \`null\`, or equals \`ORPHANED_REPORT\`.
* **Affected rows:** **${s.orphanRows}** of ${s.rows} (${round((s.orphanRows / s.rows) * 100, 1)}%) = ${s.orphanMissingRows} \`nan\` + ${s.orphanSentinelRows} \`ORPHANED_REPORT\`. Orphaned **now** (latest sweep): ${golden.orphaned_now} reports; **chronic** (orphan in ≥ 2 of the last 5 sweeps): ${golden.orphan_chronic}.
* **Treatment:** normalised to \`owner_email = NULL\` plus explicit \`is_orphan\` / \`orphan_reason\`. **Nothing deleted**; orphans stay visible in the Orphaned Reports page, where an Admin can assign an owner.
* **Rationale:** orphans are the signal the dashboard exists to expose. An "orphan if ever missing" rule would flag 94 of 100 reports (owners flip between snapshots in this synthetic file), which is useless, so the operational definition is "orphaned in the latest sweep" with "chronic" as the escalation tier.
* **Before / after:** ${s.orphanRows} rows with raw text \`nan\`/\`ORPHANED_REPORT\` → ${s.orphanRows} rows flagged, 0 removed.

## Defect 2: Negative Snowflake credits

* **Detection rule:** \`snowflake_credits_consumed < 0\`.
* **Affected rows:** **${s.quarantinedRows}**; total excluded credits **${s.negativeCreditSum}** (${round((Math.abs(s.negativeCreditSum) / s.rawCreditTotal) * 100, 4)}% of the raw total).
* **Treatment:** moved to \`DQ_QUARANTINE\` with the raw value; excluded from attribution. **No \`abs()\`, no clamping to 0** (abs would invent consumption; clamping would invent fake zero readings).
* **Before / after:** raw credit total ${s.rawCreditTotal} → clean total ${s.cleanCreditTotal} + quarantined ${s.negativeCreditSum}. Rows: ${s.rows} = ${s.cleanRows} clean + ${s.quarantinedRows} quarantined. Reconciliation: attributed + idle(0) + excluded = metered (see \`RECONCILIATION_CHECKS\`).

| snapshot_id | report | sweep | raw credits |
|---|---|---|---|
${q}

## Defect 3: Extreme latency spikes (up to ${s.latencyMax} s)

* **Detection rule:** \`avg_load_time_sec > 15\` (strict). Severity WARN (15, 30], HIGH (30, 45], CRIT > 45. "Invalid" would be ≤ 0 or > 3600 s: **0 rows** are invalid.
* **Affected rows:** **${s.latencyGt15}** over threshold (WARN ${sev.warn} / HIGH ${sev.high} / CRIT ${sev.crit}); ${s.latencyExactly15} rows are exactly 15.0 and correctly do **not** alert.
* **Treatment:** kept as valid signals; they drive alerts. **Finding:** the median latency is above 15 s, so the mandated rule fires on ${round((s.latencyGt15 / s.rows) * 100, 1)}% of rows. The threshold is configurable (\`LATENCY_*_SEC\`) and we recommend recalibrating (e.g. to p90).
* **Alert funnel (measured):** ${golden.alert_firings.latency + golden.alert_firings.refresh} firings → ${golden.alert_stored_incidents.total} stored incidents → ${golden.alert_toasts} default toasts.

## Defect 4: Active users vs AWS hosting cost discrepancy

* **Detection rules (three lenses):** (a) Pearson / R² of views vs AWS cost; (b) row-level robust z-score of ln(AWS $/view) with |z| > 3.5; (c) hard-impossible rows.
* **Results:** Pearson **${s.viewsAwsPearson}** (R² ≈ ${round(s.viewsAwsPearson ** 2, 4)}), i.e. no relationship. **${s.costOutlierRows}** row-level cost-per-view outliers; **${s.peakGtViewsRows}** rows where concurrent peak exceeds monthly views; **${s.zeroViewRows}** zero-view rows that still carry spend.
* **Treatment:** flagged, not removed; exposed at \`GET /api/costs/summary\` and on the Cost page. Report-level ratios look healthy (ratio of sums), which is why row-level checks are needed.

| snapshot_id | report | robust z |
|---|---|---|
${outl}

## Additional defects found

* **UNKNOWN refresh status:** ${s.refreshUnknown} rows. Treated as an "unverified" state: not a failure, excluded from the success-rate denominator.
* **No timestamps:** replay and trends use sweeps with synthetic timestamps.
* **Owner instability:** owners change between consecutive snapshots of the same report almost every time (a synthetic-data artefact); recommended fix is an owner registry.
* **Duplicates / bad types:** none found.
`,
);
console.log('generated docs');
