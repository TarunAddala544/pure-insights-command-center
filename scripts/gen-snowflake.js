// Generates sql/snowflake/01a_load_raw_data.sql and 99_verification.sql from the CSV and golden.json.
import fs from 'node:fs';
import path from 'node:path';
import { loadConfig } from '../backend/src/config/index.js';
import { ingest } from '../backend/src/domain/clean.js';
import { syntheticTimestamp } from '../backend/src/repositories/warehouseRepository.js';

const cfg = loadConfig();
const { rows } = ingest(cfg.csvPath);
const golden = JSON.parse(fs.readFileSync(path.join(cfg.root, 'validation/golden.json'), 'utf8'));
const out = path.join(cfg.root, 'sql/snowflake');
const q = (s) => `'${String(s).replaceAll("'", "''")}'`;

const tuple = (r) =>
  `(${r.snapshotId},${r.sweep},${q(syntheticTimestamp(r.sweep).slice(0, 19).replace('T', ' '))},${q(r.reportId)},${q(r.reportName)},${q(r.ownerRaw)},${q(r.refreshStatus)},${r.monthly_active_views},${r.snowflake_credits_consumed},${r.avg_load_time_sec},${r.aws_hosting_cost_usd},${r.query_count_last_30d},${r.concurrent_user_peak})`;

const chunks = [];
for (let i = 0; i < rows.length; i += 500) {
  chunks.push(
    `INSERT INTO RAW_REPORT_SNAPSHOTS VALUES\n${rows
      .slice(i, i + 500)
      .map(tuple)
      .join(',\n')};`,
  );
}
fs.writeFileSync(
  path.join(out, '01a_load_raw_data.sql'),
  `-- 01a_load_raw_data.sql | DIALECT: common INSERTs (GENERATED by scripts/gen-snowflake.js - do not edit)\n-- Source: data/Case_Study_3_Pure_Insights_Monitoring.csv sha256=${golden.csv_sha256}\n-- No staging or external stage needed. 2,000 rows.\n${chunks.join('\n')}\n`,
);

const checks = [
  ['raw_rows', 'SELECT COUNT(*) FROM RAW_REPORT_SNAPSHOTS', golden.rows],
  ['clean_rows', 'SELECT COUNT(*) FROM CLEAN_SNAPSHOTS', golden.clean_rows],
  ['quarantined_rows', 'SELECT COUNT(*) FROM DQ_QUARANTINE', golden.quarantined_rows],
  ['orphan_owner_rows', "SELECT affected_rows FROM V_DQ_SUMMARY WHERE defect_code = 'ORPHAN_OWNER_ROWS'", golden.orphan_rows],
  ['orphaned_now', 'SELECT COUNT(*) FROM V_ORPHANS_NOW', golden.orphaned_now],
  ['latency_gt_15s_rows', "SELECT affected_rows FROM V_DQ_SUMMARY WHERE defect_code = 'LATENCY_GT_15S'", golden.latency_gt15],
  [
    'cost_per_view_outliers',
    "SELECT affected_rows FROM V_DQ_SUMMARY WHERE defect_code = 'COST_PER_VIEW_OUTLIERS'",
    golden.cost_outliers_z35,
  ],
  ['peak_gt_views_rows', "SELECT affected_rows FROM V_DQ_SUMMARY WHERE defect_code = 'PEAK_GT_MONTHLY_VIEWS'", golden.peak_gt_views_rows],
  ['clean_credit_total', 'SELECT ROUND(SUM(credits_direct), 2) FROM REPORT_CREDIT_ATTRIBUTION', golden.clean_credit_total],
  ['negative_credit_sum', 'SELECT ROUND(SUM(raw_value), 2) FROM DQ_QUARANTINE', golden.negative_credit_sum],
  ['fleet_unit_cost_usd', 'SELECT ROUND(unit_cost_per_view_usd, 4) FROM FLEET_UNIT_ECONOMICS', golden.fleet_unit_cost],
  ['unit_cost_median_usd', 'SELECT ROUND(MEDIAN(unit_cost_per_view_usd), 4) FROM REPORT_UNIT_ECONOMICS', golden.unit_cost_median],
  ['reconciliation_failed_checks', 'SELECT COUNT(*) FROM RECONCILIATION_CHECKS WHERE passed = FALSE', 0],
];
const body = checks
  .map(
    ([name, sql, exp]) => `SELECT '${name}' AS metric, CAST((${sql}) AS DOUBLE) AS actual, CAST(${exp} AS DOUBLE) AS expected_from_pandas`,
  )
  .join('\nUNION ALL\n');
fs.writeFileSync(
  path.join(out, '99_verification.sql'),
  `-- 99_verification.sql | DIALECT: common (GENERATED by scripts/gen-snowflake.js - do not edit)\n-- One result table: download as CSV and compare to the independent pandas verifier. Credit price assumed 3.00.\nSELECT metric, actual, expected_from_pandas,\n       CASE WHEN ABS(actual - expected_from_pandas) < 0.0051 THEN 'PASS' ELSE 'FAIL' END AS status\nFROM (\n${body}\n) t\nORDER BY metric;\n`,
);
console.log('generated snowflake load + verification');
